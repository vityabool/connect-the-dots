#!/usr/bin/env node
/**
 * Writes THIRD_PARTY_LICENSES.md: the licenses of every package that ships with the product (the production dependency
 * tree of the web app and the API). Fails when a license is not known to be compatible with the MIT License, so that a new
 * dependency cannot slip in unnoticed.
 *
 *   npm run licenses            write THIRD_PARTY_LICENSES.md
 *   npm run licenses -- --check fail when the file is out of date or a license is not allowed
 */
import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'THIRD_PARTY_LICENSES.md');

/** Licenses that can be shipped inside an MIT-licensed work (permissive licenses; the GPL family is deliberately not allowed). */
const ALLOWED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'Apache-2.0', 'BlueOak-1.0.0', 'CC0-1.0', 'Unlicense', 'Python-2.0', 'MPL-2.0']);
const OWN = new Set(['connect-the-dots', '@ctd/shared', '@ctd/api', '@ctd/web', 'ctd-api']);

/** Finds an installed package the way Node does: in the nearest node_modules folder, walking up. */
function resolvePackage(name, from) {
  for (let dir = from; ; dir = dirname(dir)) {
    const candidate = join(dir, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return realpathSync(candidate);
    if (dirname(dir) === dir) return undefined;
  }
}

/** Every package that the workspaces need at run time (dependencies and installed optional dependencies, recursively). */
function productionPackages() {
  const found = new Set();
  const visit = (dir) => {
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    for (const name of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies })) {
      const target = resolvePackage(name, dir);
      if (!target || found.has(target)) continue;
      found.add(target);
      visit(target);
    }
  };
  for (const workspace of ['shared', 'api', 'web']) visit(join(root, workspace));
  return [...found];
}

const paths = productionPackages();

const rows = new Map();
for (const dir of paths) {
  const manifest = join(dir, 'package.json');
  if (!existsSync(manifest)) continue;
  const pkg = JSON.parse(readFileSync(manifest, 'utf8'));
  if (!pkg.name || OWN.has(pkg.name)) continue;
  const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (pkg.licenses ? pkg.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN');
  const repo = (typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? pkg.homepage ?? '').replace(/^git\+/, '').replace(/\.git$/, '');
  rows.set(`${pkg.name}@${pkg.version}`, { name: pkg.name, version: pkg.version, license, repo });
}

const sorted = [...rows.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

/** A license expression such as "(MIT OR Apache-2.0)" is fine when at least one alternative is allowed. */
function isAllowed(license) {
  const parts = license.replace(/[()]/g, '').split(/\s+OR\s+/i).map((p) => p.trim());
  return parts.some((part) => part.split(/\s+AND\s+/i).every((p) => ALLOWED.has(p.trim())));
}
const problems = sorted.filter((row) => !isAllowed(row.license));

const counts = new Map();
for (const row of sorted) counts.set(row.license, (counts.get(row.license) ?? 0) + 1);

const md = [
  '# Third-party licenses',
  '',
  'Connect the Dots is licensed under the [MIT License](LICENSE). It includes the following third-party',
  'packages in the product (production dependencies of the web app and the API). All of them use licenses that can be combined',
  'with the MIT License. Development tools (compilers, test runners, image tools) are not shipped and are not listed.',
  '',
  'This file is generated by `npm run licenses`; do not edit it by hand.',
  '',
  `**${sorted.length} packages**: ${[...counts].sort((a, b) => b[1] - a[1]).map(([license, n]) => `${license} (${n})`).join(', ')}`,
  '',
  '| Package | Version | License | Source |',
  '|---------|---------|---------|--------|',
  ...sorted.map((row) => `| ${row.name} | ${row.version} | ${row.license} | ${row.repo || ''} |`),
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  let failed = false;
  if (problems.length > 0) {
    console.error('Licenses that are not on the allowed list:\n' + problems.map((p) => `  ${p.name}@${p.version}: ${p.license}`).join('\n'));
    failed = true;
  }
  if (current.replace(/\r\n/g, '\n') !== md) {
    console.error('THIRD_PARTY_LICENSES.md is out of date. Run: npm run licenses');
    failed = true;
  }
  process.exit(failed ? 1 : 0);
}

writeFileSync(outFile, md);
console.log(`Wrote THIRD_PARTY_LICENSES.md (${sorted.length} packages)`);
if (problems.length > 0) {
  console.error('\nWARNING: licenses not on the allowed list (review them before publishing):\n' + problems.map((p) => `  ${p.name}@${p.version}: ${p.license}`).join('\n'));
  process.exitCode = 1;
}
